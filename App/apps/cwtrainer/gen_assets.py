"""Read-only, fixed-size UI strings. No executable code in external flash."""
from pathlib import Path
import re
HERE = Path(__file__).resolve().parent
TEXTS = {
    'MAGIC':'CT33', 'TX':'TX FREE ', 'RX':'RX TRAIN ', 'BOTH':'RX>TX RX ',
    'STRAIGHT':'STRAIGHT', 'A':'IAMB A', 'B':'IAMB B',
    'LISTEN':'LISTEN...', 'READY':'PTT RPLY', 'READY_BOTH':'7 NEW S1 REPLAY',
    'ZERO':'0 MODE', 'EDIT_RX':'LEN ', 'F':' WPM-', 'WPM':' WPM',
    'HZ':' HZ', 'OK':' OK', 'ERR':' ERR',
    'GAP_0':'GAP 1X','GAP_1':'GAP 1.5X','GAP_2':'GAP 2X','GAP_3':'GAP 3X',
}
def generate():
    data=bytearray(); header=['/* Generated by gen_assets.py. */', '#define TEXT_SIZE 16u']
    for key, value in TEXTS.items():
        encoded=value.encode('ascii'); assert len(encoded)<16
        header.append(f'#define T_{key} {len(data)//16}u')
        data.extend(encoded+b'\0'*(16-len(encoded)))
    # Pre-render command capsules using the resident 3x5 font. Assets are pixels,
    # never executable instructions. Pixel polarity matches GUI_DisplaySmallestInverse.
    font_source=(HERE.parents[1]/'font.c').read_text()
    font_source=font_source.split('const uint8_t gFont3x5[',1)[1].split('=',1)[1].split(';',1)[0]
    font_source=re.sub(r'/\*.*?\*/|//[^\n]*','',font_source,flags=re.S)
    font=[int(v,0) for v in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b',font_source)]
    assert len(font)==96*3
    header.append(f'#define GRID_OFFSET {len(data)}u')
    for mode in range(3):
        labels=['1 KEY','2 WPM','3 HZ','' if mode==0 else '4 LEN','5 SWAP','6 CLEAR',
                '' if mode==0 else '7 NEW','' if mode==0 else '8 GAP','' if mode==0 else ('9 SHOW' if mode==1 else '9 CHECK')]
        if mode==1:
            for i in (0,4,5): labels[i]=''
        for row in range(3):
            pixels=bytearray(128)
            for col in range(3):
                label=labels[row*3+col]
                if not label: continue
                x=2+43*col
                for i,c in enumerate(label):
                    for j in range(3): pixels[x+4*i+j]=font[(ord(c)-32)*3+j]<<1
                for i in range(x-2,x+39): pixels[i]^=0x3e if i in (x-2,x+38) else 0x7f
            data.extend(pixels)
    (HERE/'cwtrainer_assets.bin').write_bytes(data)
    (HERE/'cwtrainer_assets.h').write_text('\n'.join(header)+'\n')
    return data

if __name__=='__main__': generate()
